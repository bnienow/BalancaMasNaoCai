    private void tabelaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelaMouseClicked
        Orcamento orcamento = lista.get(tabela.getSelectedRow());

        txtId.setText(String.valueOf(orcamento.getIdOrcamento()));
        txtAprovacao.setValue(formataData(orcamento.getDtAprovacao()));
        selecionaResponsavel(orcamento.getIdEngenheiroResponsavel());
    }//GEN-LAST:event_tabelaMouseClicked

    public void carregaTabela() {
        DefaultTableModel modelo = (DefaultTableModel) tabela.getModel();
        modelo.setNumRows(0);

        DataSource dataSource = new DataSource();
        DaoOrcamento dao = new DaoOrcamento(dataSource);
        lista = dao.consulta(txtBusca.getText());

        for (Orcamento item : lista) {
            modelo.addRow(new Object[]{
                item.getIdOrcamento(),
                formataData(item.getDtAprovacao()),
                item.getDsNomeResponsavel()
            });
        }
    }

    public void limpaCampos() {
        txtId.setText("");
        txtAprovacao.setValue(null);
    }

    public void carregaResponsaveis() {
        DataSource dataSource = new DataSource();
        DaoEngenheiro dao = new DaoEngenheiro(dataSource);

        for (Engenheiro item : dao.consulta("")) {
            cbResponsavel.addItem(item);
        }
    }

    public void selecionaResponsavel(int codigo) {
        for (int i = 0; i < cbResponsavel.getItemCount(); i++) {
            if (cbResponsavel.getItemAt(i).getIdEngenheiro() == codigo) {
                cbResponsavel.setSelectedIndex(i);
            }
        }
    }

    public LocalDate leData(javax.swing.JFormattedTextField campo) {
        if (campo.getText().replace("/", "").trim().isEmpty()) {
            return null;
        }
        return LocalDate.parse(campo.getText(), formato);
    }

    public String formataData(LocalDate data) {
        if (data == null) {
            return "";
        }
        return data.format(formato);
    }

