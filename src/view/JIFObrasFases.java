    private void btnIncluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIncluirActionPerformed
        Obra obra = (Obra) cbObra.getSelectedItem();
        Fase fase = (Fase) cbFase.getSelectedItem();

        ObraFase obraFase = new ObraFase();
        obraFase.setIdObra(obra.getIdObra());
        obraFase.setIdFase(fase.getIdFase());
        obraFase.setDtInicioFase(leData(txtInicio));
        obraFase.setDtTerminoFase(leData(txtTermino));

        DataSource dataSource = new DataSource();
        DaoObraFase dao = new DaoObraFase(dataSource);
        dao.incluir(obraFase);

        limpaCampos();
        carregaTabela();
    }//GEN-LAST:event_btnIncluirActionPerformed

