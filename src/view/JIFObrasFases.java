    private void tabelaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelaMouseClicked
        ObraFase obraFase = lista.get(tabela.getSelectedRow());

        selecionaObra(obraFase.getIdObra());
        selecionaFase(obraFase.getIdFase());
        txtInicio.setValue(formataData(obraFase.getDtInicioFase()));
        txtTermino.setValue(formataData(obraFase.getDtTerminoFase()));
    }//GEN-LAST:event_tabelaMouseClicked

    public void carregaTabela() {
        DefaultTableModel modelo = (DefaultTableModel) tabela.getModel();
        modelo.setNumRows(0);

        DataSource dataSource = new DataSource();
        DaoObraFase dao = new DaoObraFase(dataSource);
        lista = dao.consulta(txtBusca.getText());

        for (ObraFase item : lista) {
            modelo.addRow(new Object[]{
                item.getDescricaoObra(),
                item.getDsFase(),
                formataData(item.getDtInicioFase()),
                formataData(item.getDtTerminoFase())
            });
        }
    }

    public void limpaCampos() {
        txtInicio.setValue(null);
        txtTermino.setValue(null);
    }

    public void carregaObras() {
        DataSource dataSource = new DataSource();
        DaoObra dao = new DaoObra(dataSource);

        for (Obra item : dao.consulta("")) {
            cbObra.addItem(item);
        }
    }

    public void selecionaObra(int codigo) {
        for (int i = 0; i < cbObra.getItemCount(); i++) {
            if (cbObra.getItemAt(i).getIdObra() == codigo) {
                cbObra.setSelectedIndex(i);
            }
        }
    }

    public void carregaFases() {
        DataSource dataSource = new DataSource();
        DaoFase dao = new DaoFase(dataSource);

        for (Fase item : dao.consulta("")) {
            cbFase.addItem(item);
        }
    }

    public void selecionaFase(int codigo) {
        for (int i = 0; i < cbFase.getItemCount(); i++) {
            if (cbFase.getItemAt(i).getIdFase() == codigo) {
                cbFase.setSelectedIndex(i);
            }
        }
    }

    public LocalDate leData(javax.swing.JFormattedTextField campo) {
        if (campo.getText().replace("/", "").trim().isEmpty()) {
            return null;
        }
        return LocalDate.parse(campo.getText(), formato);
    }

    public String formataData(LocalDate data) {
        if (data == null) {
            return "";
        }
        return data.format(formato);
    }

