    private void btnIncluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIncluirActionPerformed
        Orcamento orcamento = (Orcamento) cbOrcamento.getSelectedItem();
        Obra obra = (Obra) cbObra.getSelectedItem();

        OrcamentoObra orcamentoObra = new OrcamentoObra();
        orcamentoObra.setIdOrcamento(orcamento.getIdOrcamento());
        orcamentoObra.setIdObra(obra.getIdObra());
        orcamentoObra.setDtInicio(leData(txtInicio));
        orcamentoObra.setDtFim(leData(txtFim));
        orcamentoObra.setVlPrevisto(Double.parseDouble(txtPrevisto.getText().replace(",", ".")));
        orcamentoObra.setVlRealizado(Double.parseDouble(txtRealizado.getText().replace(",", ".")));

        DataSource dataSource = new DataSource();
        DaoOrcamentoObra dao = new DaoOrcamentoObra(dataSource);
        dao.incluir(orcamentoObra);

        limpaCampos();
        carregaTabela();
    }//GEN-LAST:event_btnIncluirActionPerformed

