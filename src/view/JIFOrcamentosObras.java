    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        Orcamento orcamento = (Orcamento) cbOrcamento.getSelectedItem();
        Obra obra = (Obra) cbObra.getSelectedItem();

        int opcao = JOptionPane.showConfirmDialog(null, "Deseja excluir esta previsão?", "Atenção", JOptionPane.YES_NO_OPTION);

        if (opcao == JOptionPane.YES_OPTION) {
            DataSource dataSource = new DataSource();
            DaoOrcamentoObra dao = new DaoOrcamentoObra(dataSource);
            dao.excluir(orcamento.getIdOrcamento(), obra.getIdObra());

            limpaCampos();
            carregaTabela();
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

