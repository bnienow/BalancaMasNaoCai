    private void tabelaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelaMouseClicked
        OrcamentoObra orcamentoObra = lista.get(tabela.getSelectedRow());

        selecionaOrcamento(orcamentoObra.getIdOrcamento());
        selecionaObra(orcamentoObra.getIdObra());
        txtInicio.setValue(formataData(orcamentoObra.getDtInicio()));
        txtFim.setValue(formataData(orcamentoObra.getDtFim()));
        txtPrevisto.setText(String.format("%.2f", orcamentoObra.getVlPrevisto()));
        txtRealizado.setText(String.format("%.2f", orcamentoObra.getVlRealizado()));
    }//GEN-LAST:event_tabelaMouseClicked

    public void carregaTabela() {
        DefaultTableModel modelo = (DefaultTableModel) tabela.getModel();
        modelo.setNumRows(0);

        DataSource dataSource = new DataSource();
        DaoOrcamentoObra dao = new DaoOrcamentoObra(dataSource);
        lista = dao.consulta(txtBusca.getText());

        for (OrcamentoObra item : lista) {
            modelo.addRow(new Object[]{
                item.getIdOrcamento(),
                item.getDescricaoObra(),
                formataData(item.getDtInicio()),
                formataData(item.getDtFim()),
                String.format("%.2f", item.getVlPrevisto()),
                String.format("%.2f", item.getVlRealizado())
            });
        }
    }

    public void limpaCampos() {
        txtInicio.setValue(null);
        txtFim.setValue(null);
        txtPrevisto.setText("");
        txtRealizado.setText("");
    }

    public void carregaOrcamentos() {
        DataSource dataSource = new DataSource();
        DaoOrcamento dao = new DaoOrcamento(dataSource);

        for (Orcamento item : dao.consulta("")) {
            cbOrcamento.addItem(item);
        }
    }

    public void selecionaOrcamento(int codigo) {
        for (int i = 0; i < cbOrcamento.getItemCount(); i++) {
            if (cbOrcamento.getItemAt(i).getIdOrcamento() == codigo) {
                cbOrcamento.setSelectedIndex(i);
            }
        }
    }

    public void carregaObras() {
        DataSource dataSource = new DataSource();
        DaoObra dao = new DaoObra(dataSource);

        for (Obra item : dao.consulta("")) {
            cbObra.addItem(item);
        }
    }

    public void selecionaObra(int codigo) {
        for (int i = 0; i < cbObra.getItemCount(); i++) {
            if (cbObra.getItemAt(i).getIdObra() == codigo) {
                cbObra.setSelectedIndex(i);
            }
        }
    }

    public LocalDate leData(javax.swing.JFormattedTextField campo) {
        if (campo.getText().replace("/", "").trim().isEmpty()) {
            return null;
        }
        return LocalDate.parse(campo.getText(), formato);
    }

    public String formataData(LocalDate data) {
        if (data == null) {
            return "";
        }
        return data.format(formato);
    }

