    private void tabelaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelaMouseClicked
        ObraEngenheiro obraEngenheiro = lista.get(tabela.getSelectedRow());

        selecionaObra(obraEngenheiro.getIdObra());
        selecionaEngenheiro(obraEngenheiro.getIdEngenheiro());
        selecionaFuncao(obraEngenheiro.getIdFuncao());
        txtAdmissao.setText(formataData(obraEngenheiro.getDtAdmissaoEngenheiro()));
        txtInicio.setValue(formataData(obraEngenheiro.getDtInicioTrabalho()));
        txtFim.setValue(formataData(obraEngenheiro.getDtFimTrabalho()));
    }//GEN-LAST:event_tabelaMouseClicked

