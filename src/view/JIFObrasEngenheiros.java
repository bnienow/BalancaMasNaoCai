    private void btnIncluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIncluirActionPerformed
        Obra obra = (Obra) cbObra.getSelectedItem();
        Engenheiro eng = (Engenheiro) cbEngenheiro.getSelectedItem();
        Funcao funcao = (Funcao) cbFuncao.getSelectedItem();

        ObraEngenheiro obraEngenheiro = new ObraEngenheiro();
        obraEngenheiro.setIdObra(obra.getIdObra());
        obraEngenheiro.setIdEngenheiro(eng.getIdEngenheiro());
        obraEngenheiro.setDtAdmissaoEngenheiro(eng.getDtAdmissao());
        obraEngenheiro.setIdFuncao(funcao.getIdFuncao());
        obraEngenheiro.setDtInicioTrabalho(leData(txtInicio));
        obraEngenheiro.setDtFimTrabalho(leData(txtFim));

        DataSource dataSource = new DataSource();
        DaoObraEngenheiro dao = new DaoObraEngenheiro(dataSource);
        dao.incluir(obraEngenheiro);

        limpaCampos();
        carregaTabela();
    }//GEN-LAST:event_btnIncluirActionPerformed

