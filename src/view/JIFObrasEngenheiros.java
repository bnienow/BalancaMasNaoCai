    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        Obra obra = (Obra) cbObra.getSelectedItem();
        Engenheiro eng = (Engenheiro) cbEngenheiro.getSelectedItem();

        int opcao = JOptionPane.showConfirmDialog(null, "Deseja retirar este engenheiro da obra?", "Atenção", JOptionPane.YES_NO_OPTION);

        if (opcao == JOptionPane.YES_OPTION) {
            DataSource dataSource = new DataSource();
            DaoObraEngenheiro dao = new DaoObraEngenheiro(dataSource);
            dao.excluir(obra.getIdObra(), eng.getIdEngenheiro());

            limpaCampos();
            carregaTabela();
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

