    private void tabelaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelaMouseClicked
        int linha = tabela.getSelectedRow();

        txtId.setText(tabela.getValueAt(linha, 0).toString());
        txtNome.setText(tabela.getValueAt(linha, 1).toString());
        txtCrea.setText(tabela.getValueAt(linha, 2).toString());
        txtAdmissao.setText(tabela.getValueAt(linha, 3).toString());
    }//GEN-LAST:event_tabelaMouseClicked

    public void carregaTabela() {
        DefaultTableModel modelo = (DefaultTableModel) tabela.getModel();
        modelo.setNumRows(0);

        DataSource dataSource = new DataSource();
        DaoEngenheiro dao = new DaoEngenheiro(dataSource);

        for (Engenheiro e : dao.consulta(txtBusca.getText())) {
            modelo.addRow(new Object[]{
                e.getIdEngenheiro(),
                e.getDsNome(),
                e.getNrCREA(),
                e.getDtAdmissao().format(formato)
            });
        }
    }

    public void limpaCampos() {
        txtId.setText("");
        txtNome.setText("");
        txtCrea.setText("");
        txtAdmissao.setValue(null);
    }

