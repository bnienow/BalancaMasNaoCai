    private void btnIncluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIncluirActionPerformed
        Engenheiro eng = (Engenheiro) cbEngenheiro.getSelectedItem();

        Obra obra = new Obra();
        obra.setDescricao(txtDescricao.getText());
        obra.setDtInicio(leData(txtInicio));
        obra.setDtFim(leData(txtFim));
        obra.setIdEngenheiro(eng.getIdEngenheiro());
        obra.setNrCrea(eng.getNrCREA());
        obra.setDtAdmissaoEngenheiro(eng.getDtAdmissao());

        DataSource dataSource = new DataSource();
        DaoObra dao = new DaoObra(dataSource);
        dao.incluir(obra);

        limpaCampos();
        carregaTabela();
    }//GEN-LAST:event_btnIncluirActionPerformed

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        if (txtId.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Selecione uma obra na tabela!");
        } else {
            Engenheiro eng = (Engenheiro) cbEngenheiro.getSelectedItem();

            Obra obra = new Obra();
            obra.setIdObra(Integer.parseInt(txtId.getText()));
            obra.setDescricao(txtDescricao.getText());
            obra.setDtInicio(leData(txtInicio));
            obra.setDtFim(leData(txtFim));
            obra.setIdEngenheiro(eng.getIdEngenheiro());
            obra.setNrCrea(eng.getNrCREA());
            obra.setDtAdmissaoEngenheiro(eng.getDtAdmissao());

            DataSource dataSource = new DataSource();
            DaoObra dao = new DaoObra(dataSource);
            dao.alterar(obra);

            limpaCampos();
            carregaTabela();
        }
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (txtId.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Selecione uma obra na tabela!");
        } else {
            int opcao = JOptionPane.showConfirmDialog(null, "Deseja excluir esta obra?", "Atenção", JOptionPane.YES_NO_OPTION);

            if (opcao == JOptionPane.YES_OPTION) {
                DataSource dataSource = new DataSource();
                DaoObra dao = new DaoObra(dataSource);
                dao.excluir(Integer.parseInt(txtId.getText()));

                limpaCampos();
                carregaTabela();
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

